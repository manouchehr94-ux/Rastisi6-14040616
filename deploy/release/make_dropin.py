#!/usr/bin/env python3
"""Compute the systemd drop-in that moves an EXISTING unit onto the release layout, from the unit's own text (standard library only).

    systemctl cat rastisi-rc-20261111.service > unit.txt
    make_dropin.py --unit-file unit.txt --base /srv/rastisi-releases --old-app /srv/rastisi-rc-20261111

It only rewrites the PATHS that point into the old directory (the interpreter / gunicorn binary and the working directory); every other
flag of ExecStart (bind address, workers, timeouts, logs) is copied verbatim, so the service keeps behaving as it does today.
Prints the drop-in and a before/after of the effective command. It changes nothing on the machine.
"""

import argparse
import re
import sys
from pathlib import Path


def parse_directives(text, names):
    found = {}
    for line in text.splitlines():
        stripped = line.strip()
        for name in names:
            if stripped.startswith(name + "="):
                found[name] = stripped[len(name) + 1:]          # the LAST definition wins, like systemd
    return found


def build_dropin(unit_text, base, old_app):
    d = parse_directives(unit_text, ("ExecStart", "WorkingDirectory", "User", "EnvironmentFile"))
    if not d.get("ExecStart"):
        raise SystemExit("the unit has no ExecStart=")
    old_app = old_app.rstrip("/")
    exec_start = d["ExecStart"].lstrip("-@+!:")
    binary = exec_start.split()[0]
    if not binary.startswith(old_app + "/") or not binary.endswith("/gunicorn"):
        raise SystemExit("ExecStart does not start %s/<venv>/bin/gunicorn (found %r): adapt by hand, this tool will not guess" % (old_app, binary))
    new_binary = "%s/current/venv/bin/gunicorn" % base.rstrip("/")
    new_exec = exec_start.replace(binary, new_binary, 1)
    # any other path inside the old application directory (e.g. a --config file) must move too
    leftovers = re.findall(re.escape(old_app) + r"[^\s\"']*", new_exec)
    if leftovers:
        raise SystemExit("ExecStart still references the old directory after the rewrite: %s. Decide by hand where those files should live." % leftovers[0])
    workdir = d.get("WorkingDirectory", "")
    if workdir and workdir.rstrip("/") not in (old_app,):
        raise SystemExit("WorkingDirectory=%s is not the old application directory %s: adapt by hand" % (workdir, old_app))
    lines = ["# Generated by deploy/release/make_dropin.py. Moves the unit onto the release layout; everything else in the unit is unchanged.",
             "[Service]", "WorkingDirectory=", "WorkingDirectory=%s/current/app" % base.rstrip("/"), "ExecStart=", "ExecStart=%s" % new_exec]
    return "\n".join(lines) + "\n", d, exec_start, new_exec


def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument("--unit-file", required=True)
    ap.add_argument("--base", required=True, help="the release base directory (deploy.conf base_dir)")
    ap.add_argument("--old-app", required=True, help="the directory the service runs from today")
    ap.add_argument("--out", help="write the drop-in here instead of printing it")
    args = ap.parse_args(argv)
    dropin, d, before, after = build_dropin(Path(args.unit_file).read_text(encoding="utf-8"), args.base, args.old_app)
    sys.stderr.write("BEFORE  ExecStart=%s\n        WorkingDirectory=%s\nAFTER   ExecStart=%s\n        WorkingDirectory=%s/current/app\n" % (
        before, d.get("WorkingDirectory", "(unset)"), after, args.base.rstrip("/")))
    if d.get("User"):
        sys.stderr.write("User=%s (unchanged: it must be the app_user of deploy.conf)\n" % d["User"])
    if args.out:
        Path(args.out).write_text(dropin, encoding="utf-8")
    else:
        sys.stdout.write(dropin)
    return 0


if __name__ == "__main__":
    sys.exit(main())
