class MediaZipUnitTests(TestCase):
    """The archive reader: unusual but legitimate layouts are accepted, hostile ones refused."""

    def setUp(self):
        self.tmp = Path(tempfile.mkdtemp())
        self.addCleanup(shutil.rmtree, self.tmp, ignore_errors=True)

    def make(self, names, *, mutate=None):
        import zipfile

        path = self.tmp / "m.zip"
        with zipfile.ZipFile(path, "w") as zf:
            for name, data in names.items():
                zf.writestr(name, data)
        if mutate:
            path.write_bytes(mutate(path.read_bytes()))
        return path

    def open(self, path):
        from apps.stores.services.demo_bundle.media_zip import MediaZip

        return MediaZip(path)

    def test_nfd_names_from_macos_match_nfc_database_values(self):
        import unicodedata

        zf = self.open(self.make({unicodedata.normalize("NFD", "media/caf\u00e9.png"): b"x"}))
        self.assertEqual(zf.detect_prefix({"caf\u00e9.png"}), "media/")
        self.assertIsNotNone(zf.info_for("caf\u00e9.png"))

    def test_windows_backslash_separators(self):
        zf = self.open(self.make({"media\\products\\a.png": b"x"}))
        self.assertEqual(zf.detect_prefix({"products/a.png"}), "media/")

    def test_legacy_oem_encoded_persian_names(self):
        """Old Windows zippers store UTF-8 bytes WITHOUT the UTF-8 flag; Python then decodes them as cp437."""
        name = "products/\u06a9\u06cc\u0641.png"  # کیف.png
        import zipfile

        path = self.tmp / "legacy.zip"
        with zipfile.ZipFile(path, "w") as zf:
            zf.writestr(zipfile.ZipInfo("PLACEHOLDER-NAME-LONG-ENOUGH-FOR-REPLACE.png"), b"x")
        data = path.read_bytes()
        old = b"PLACEHOLDER-NAME-LONG-ENOUGH-FOR-REPLACE.png"
        new = name.encode("utf-8")
        new = new + b"_" * (len(old) - len(new))
        self.assertEqual(len(new), len(old))
        path.write_bytes(data.replace(old, new))
        zf = self.open(path)
        # stored bytes are UTF-8 without the flag -> the member is reachable through the re-decoded variant
        entry_names = list(zf.entries)
        self.assertTrue(any(n.startswith("products/\u06a9\u06cc\u0641.png") for n in entry_names), entry_names)

    def test_junk_is_ignored_and_outside_root_files_are_not_media(self):
        zf = self.open(self.make({"media/a.png": b"x", "Thumbs.db": b"j", "__MACOSX/._a": b"j", "readme.txt": b"r"}))
        zf.detect_prefix({"a.png"})
        self.assertEqual(zf.junk, 2)
        self.assertEqual(set(zf.rooted_files()), {"a.png"})

    def test_path_traversal_symlink_and_encryption_are_refused(self):
        from apps.stores.services.demo_bundle.media_zip import MediaZipError
        import zipfile

        with self.assertRaises(MediaZipError):
            self.open(self.make({"../evil.png": b"x"}))
        with self.assertRaises(MediaZipError):
            self.open(self.make({"/abs/evil.png": b"x"}))
        with self.assertRaises(MediaZipError):
            self.open(self.make({"C:/evil.png": b"x"}))
        link = self.tmp / "link.zip"
        with zipfile.ZipFile(link, "w") as zf:
            info = zipfile.ZipInfo("a.png")
            info.external_attr = (0o120777 << 16)
            zf.writestr(info, "target")
        with self.assertRaises(MediaZipError):
            self.open(link)

    def test_not_a_zip_and_missing_file(self):
        from apps.stores.services.demo_bundle.media_zip import MediaZipError

        bad = self.tmp / "bad.zip"
        bad.write_bytes(b"nope")
        with self.assertRaises(MediaZipError):
            self.open(bad)
        with self.assertRaises(MediaZipError):
            self.open(self.tmp / "missing.zip")

    def test_best_prefix_wins_and_no_match_gives_empty_root(self):
        zf = self.open(self.make({"a/b/x.png": b"1", "a/b/y.png": b"2", "other/x.png": b"3"}))
        self.assertEqual(zf.detect_prefix({"x.png", "y.png"}), "a/b/")
        self.assertEqual(zf.detect_prefix({"zzz.png"}), "")
