def sha(path):
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()


@unittest.skipUnless(connection.vendor == "sqlite", "source databases are built by dumping the SQLite test database")
@override_settings(ALLOWED_HOSTS=HOSTS, RASTISI_ADMIN_DOMAIN_SUFFIX="rastisi.ir")
class ConverterBase(TestCase):
    """Builds the two independent source databases ONCE per class."""

    @classmethod
    def setUpTestData(cls):
        cls.root = Path(tempfile.mkdtemp(prefix="conv-tests-"))
        cls.media_a, cls.media_b = cls.root / "media_a", cls.root / "media_b"
        cls.media_a.mkdir()
        cls.media_b.mkdir()
        cls.sqlite_a, cls.sqlite_b = cls.root / "demo_v5.sqlite3", cls.root / "demo_arch02.sqlite3"
        with override_settings(MEDIA_ROOT=str(cls.media_a)):
            fx.build_source_sqlite(cls.sqlite_a, cls.media_a, lambda: fx.build_rich_store("alpha", color="#aa0000", product_count=4))
        # same file name, DIFFERENT bytes -> must be renamed by the converter
        with override_settings(MEDIA_ROOT=str(cls.media_b)):
            fx.build_source_sqlite(cls.sqlite_b, cls.media_b, lambda: fx.build_rich_store("beta", color="#0000bb", product_count=5))
        (cls.media_b / "media-assets" / "shared-banner.png").write_bytes(fx.png_bytes((250, 1, 1), (64, 32)))
        cls.zip_a, cls.zip_b = cls.root / "demo_v5_media.zip", cls.root / "demo_arch02_media.zip"
        fx.zip_media(cls.media_a, cls.zip_a, wrapper="media")
        fx.zip_media(cls.media_b, cls.zip_b, wrapper="demo_arch02_media/media", backslashes=True)
        cls.hashes_before = {p.name: sha(p) for p in (cls.sqlite_a, cls.sqlite_b, cls.zip_a, cls.zip_b)}

    @classmethod
    def tearDownClass(cls):
        shutil.rmtree(cls.root, ignore_errors=True)
        super().tearDownClass()

    def setUp(self):
        cache.clear()
        self.work = Path(tempfile.mkdtemp(prefix="conv-work-"))
        self.addCleanup(shutil.rmtree, self.work, ignore_errors=True)
        self.out = self.work / "bundle"

    def specs(self, **overrides):
        return [
            SourceSpec("demo_v5", overrides.get("sqlite_a", self.sqlite_a), overrides.get("zip_a", self.zip_a)),
            SourceSpec("demo_arch02", overrides.get("sqlite_b", self.sqlite_b), overrides.get("zip_b", self.zip_b)),
        ]

    def run_convert(self, specs=None, **opts):
        return convert(specs or self.specs(), self.out, targets=TARGETS, options=ConvertOptions(**opts),
                       work_dir=self.work / "w")

    def data(self, key):
        return json.loads((self.out / "stores" / key / "data.json").read_text(encoding="utf-8"))

    def manifest(self):
        return json.loads((self.out / "manifest.json").read_text(encoding="utf-8"))


class SourceFixtureTests(ConverterBase):
    def test_fixture_sources_really_collide(self):
        import sqlite3

        def pks(path, table):
            con = sqlite3.connect(str(path))
            try:
                return {r[0] for r in con.execute(
                    f"select id from {table} where store_id in (select id from stores_store where slug in ('alpha','beta'))")}
            finally:
                con.close()

        for table in ("catalog_product", "catalog_category", "catalog_vendor"):
            a, b = pks(self.sqlite_a, table), pks(self.sqlite_b, table)
            self.assertTrue(a and b and a & b, f"{table}: the two independent databases must share primary keys")


class ConvertTests(ConverterBase):
    def test_convert_passes_and_originals_are_untouched(self):
        result = self.run_convert()
        self.assertEqual(result.report.status, PASS, result.report.to_text())
        self.assertTrue((self.out / "manifest.json").is_file())
        after = {p.name: sha(p) for p in (self.sqlite_a, self.sqlite_b, self.zip_a, self.zip_b)}
        self.assertEqual(after, self.hashes_before, "source files must never be modified")

    def test_project_database_is_never_queried(self):
        with CaptureQueriesContext(connection) as ctx:
            result = self.run_convert()
        self.assertEqual(result.report.status, PASS, result.report.to_text())
        self.assertEqual(len(ctx.captured_queries), 0, [q["sql"][:80] for q in ctx.captured_queries[:3]])

    def test_ids_are_disjoint_first_store_unchanged_second_shifted(self):
        result = self.run_convert()
        stride = result.stride
        self.assertEqual(result.offsets, {"demo_v5": 0, "demo_arch02": stride})
        a, b = self.data("demo_v5"), self.data("demo_arch02")
        pk_a = {(r["model"], r["pk"]) for r in a}
        pk_b = {(r["model"], r["pk"]) for r in b}
        self.assertFalse(pk_a & pk_b)
        self.assertTrue(all(pk < stride for _, pk in pk_a))
        self.assertTrue(all(pk > stride for _, pk in pk_b))
        self.assertEqual(self.manifest()["conversion"]["stride"], stride)

    def test_nothing_is_dropped(self):
        result = self.run_convert()
        self.assertEqual(result.report.status, PASS)
        for key, slug in (("demo_v5", "alpha"), ("demo_arch02", "beta")):
            counts = self.manifest()["stores"][key]["counts"]
            self.assertEqual(counts["storefront_builder.StorefrontLayoutVersion"], 3)  # archived + published + draft
            self.assertEqual(counts["storefront_builder.StorefrontPage"], 18)  # 3 versions x 6 page types
            self.assertEqual(counts["content.HeroSlide"], 1)
            self.assertEqual(counts["content.MediaAsset"], 2)
            self.assertEqual(counts["core.ShopSettings"], 1)
            self.assertEqual(counts["content.FooterSettings"], 1)
            self.assertEqual(counts["content.Menu"], 2)
            self.assertEqual(counts["catalog.ProductVariant"], 2)
        statuses = {
            r["fields"]["status"] for r in self.data("demo_arch02") if r["model"] == "storefront_builder.storefrontlayoutversion"
        }
        self.assertEqual(statuses, {"archived", "published", "draft"})

    def test_every_reference_kind_is_rewritten_in_every_version(self):
        self.run_convert()
        b = self.data("demo_arch02")
        pks = {}
        for r in b:
            pks.setdefault(r["model"], set()).add(r["pk"])
        from apps.stores.services.demo_bundle import remap

        seen = {}
        for r in b:
            if r["model"] != "storefront_builder.storefrontsection":
                continue
            for key, target, pk in remap.json_refs(r["fields"]["settings"]):
                seen.setdefault(key, 0)
                seen[key] += 1
                self.assertIn(pk, pks[target.lower()], f"{key} -> {target} #{pk} does not resolve after the remap")
        for key in ("product_ids", "source_id", "category_ids", "brand_ids", "collection_ids", "menu_id",
                    "media_asset_id", "destination_id"):
            self.assertIn(key, seen, f"fixture must exercise {key}")
        # foreign keys too
        for r in b:
            if r["model"] == "catalog.product":
                self.assertIn(r["fields"]["category"], pks["catalog.category"])
                self.assertIn(r["fields"]["brand"], pks["catalog.brand"])
            if r["model"] == "content.heroslide":
                self.assertIn(r["fields"]["desktop_asset"], pks["content.mediaasset"])
                self.assertIn(r["fields"]["destination_product"], pks["catalog.product"])

    def test_variant_combination_key_is_rebuilt_from_shifted_ids(self):
        self.run_convert()
        for key in ("demo_v5", "demo_arch02"):
            records = self.data(key)
            by_variant = {}
            for r in records:
                if r["model"] == "catalog.variantoptionvalue":
                    by_variant.setdefault(r["fields"]["variant"], []).append(r["fields"]["option_value"])
            variants = [r for r in records if r["model"] == "catalog.productvariant"]
            self.assertTrue(variants)
            for v in variants:
                expected = "-".join(str(x) for x in sorted(by_variant[v["pk"]]))
                self.assertEqual(v["fields"]["combination_key"], expected)

    def test_secrets_never_reach_the_bundle(self):
        self.run_convert()
        text = (self.out / "stores" / "demo_v5" / "data.json").read_text(encoding="utf-8")
        self.assertNotIn("SECRET-DO-NOT-EXPORT", text)
        self.assertNotIn("kavenegar", text)


class ConvertMediaTests(ConverterBase):
    def test_zip_layouts_are_detected_and_junk_ignored(self):
        result = self.run_convert()
        self.assertEqual(result.report.status, PASS, result.report.to_text())
