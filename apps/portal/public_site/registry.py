"""Single source of truth for everything the platform owner can edit on the
public marketing website: the shipped default of every text, colour, font and
image reference, plus how the Platform Admin editor groups and labels them.

Templates never hard-code editable copy; they ask for ``{% ps 'home.hero.title' %}``.
A missing/empty override always resolves to the default defined here, so an empty
database renders the complete shipped design and "reset" is just deleting a row.

Tokens usable inside any text default/override:
    {trial}         -> default trial length in days (Persian digits), from PlatformConfiguration
    {support_phone} -> PlatformConfiguration.support_contact_phone
    {support_email} -> PlatformConfiguration.support_contact_email
"""

from typing import NamedTuple

from apps.portal.models import PublicSitePhoto

KIND_TEXT = "text"
KIND_TEXTAREA = "textarea"
KIND_COLOR = "color"
KIND_URL = "url"
KIND_BOOL = "bool"
KIND_CHOICE = "choice"
KIND_PHOTO = "photo"   # choice of a PublicSitePhoto slot


class Field(NamedTuple):
    key: str
    label: str
    default: str
    kind: str = KIND_TEXT
    help: str = ""
    choices: tuple = ()


class Section(NamedTuple):
    title: str
    fields: tuple
    note: str = ""


class Group(NamedTuple):
    slug: str
    title: str
    blurb: str
    sections: tuple
    preview: str = "/"   # public path of the page this group controls (opened on the platform host)


class ListSpec(NamedTuple):
    prefix: str
    count: int
    names: tuple          # ordered scalar field names
    primary: str          # an item whose primary value is empty is not rendered
    kinds: dict           # name -> kind
    sub: tuple = ()       # (name, count, (subnames...), subprimary) for nested rows


FIELDS: dict[str, Field] = {}
LISTS: dict[str, ListSpec] = {}
GROUPS: list[Group] = []

PHOTO_SLOTS = tuple(PublicSitePhoto.SLOT_CHOICES)
PHOTO_CHOICES = tuple((slot, label) for slot, label in PHOTO_SLOTS if slot != "logo")


def _register(*fields: Field) -> tuple:
    for f in fields:
        if f.key in FIELDS:
            raise RuntimeError(f"duplicate public-site key: {f.key}")
        FIELDS[f.key] = f
    return fields


def t(key, label, default, kind=KIND_TEXT, help="", choices=()):
    return Field(key, label, default, kind, help, choices)


def txt(key, label, default, help=""):
    return t(key, label, default, KIND_TEXT, help)


def area(key, label, default, help=""):
    return t(key, label, default, KIND_TEXTAREA, help)


def url(key, label, default="", help=""):
    return t(key, label, default, KIND_URL, help)


def section(title, *fields, note=""):
    return Section(title, _register(*fields), note)


def items(prefix, noun, spec, rows, *, spare=0, primary=None, sub=None):
    """Build one Section per list item. ``spec`` = ((name, label[, kind[, choices]]), ...);
    ``rows`` = default tuples (same order); ``spare`` extra empty slots the owner can fill.
    Every item also gets a ``hide`` switch."""
    names = tuple(s[0] for s in spec)
    kinds = {s[0]: (s[2] if len(s) > 2 else KIND_TEXT) for s in spec}
    total = len(rows) + spare
    sub_spec = ()
    if sub:
        sub_name, sub_count, sub_names, sub_primary = sub
        sub_kinds = {sn[0]: (sn[2] if len(sn) > 2 else KIND_TEXT) for sn in sub_names}
        sub_spec = (sub_name, sub_count, tuple(sn[0] for sn in sub_names), sub_primary, sub_kinds)
    LISTS[prefix] = ListSpec(prefix, total, names, primary or names[0], kinds, sub_spec)
    sections = []
    for i in range(1, total + 1):
        row = rows[i - 1] if i <= len(rows) else ("",) * len(spec)
        fields = []
        for s, default in zip(spec, row):
            name, label = s[0], s[1]
            kind = s[2] if len(s) > 2 else KIND_TEXT
            choices = s[3] if len(s) > 3 else ()
            fields.append(Field(f"{prefix}.{i}.{name}", label, default, kind, "", choices))
        if sub:
            sub_defaults = row[len(spec)] if len(row) > len(spec) else ()
            for j in range(1, sub_count + 1):
                pair = sub_defaults[j - 1] if j <= len(sub_defaults) else ("",) * len(sub_names)
                for sn, sdefault in zip(sub_names, pair):
                    skind = sn[2] if len(sn) > 2 else KIND_TEXT
                    schoices = sn[3] if len(sn) > 3 else ()
                    fields.append(Field(f"{prefix}.{i}.{sub_name}{j}.{sn[0]}", f"{sn[1]} {j}", sdefault, skind, "", schoices))
        fields.append(Field(f"{prefix}.{i}.hide", "پنهان شود", "", KIND_BOOL))
        sections.append(Section(f"{noun} {i}", _register(*fields)))
    return tuple(sections)


